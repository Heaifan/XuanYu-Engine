[CmdletBinding()]
param([switch]$Generate)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$artifactRoot = Join-Path $root '.xye-artifacts\shader-build'
$compiler = 'E:\MyApp\sdk-vulkan\Bin\glslc.exe'
if (-not (Test-Path -LiteralPath $compiler)) { throw "glslc not found: $compiler" }
New-Item -ItemType Directory -Force -Path $artifactRoot | Out-Null
$modules = @(
    @{ Source='EditorOverlay/editor_map_label.frag'; Output='Generated/EditorOverlays/ShaderBytecode.EditorMapLabelFrag.cs'; Class='ShaderBytecodeEditorMapLabelFrag' },
    @{ Source='EditorOverlay/editor_map_label.vert'; Output='Generated/EditorOverlays/ShaderBytecode.EditorMapLabelVert.cs'; Class='ShaderBytecodeEditorMapLabelVert' },
    @{ Source='EditorOverlay/editor_nav_gizmo.frag'; Output='Generated/Navigation/ShaderBytecode.NavGizmoFrag.cs'; Class='ShaderBytecodeNavGizmoFrag' },
    @{ Source='EditorOverlay/editor_nav_gizmo.vert'; Output='Generated/Navigation/ShaderBytecode.NavGizmoVert.cs'; Class='ShaderBytecodeNavGizmoVert' },
    @{ Source='ReferenceGrid/editor_reference_grid.vert'; Output='Generated/GridTerrain/ShaderBytecode.GridVert.cs'; Class='ShaderBytecodeGridVert' },
    @{ Source='ReferenceGrid/editor_view_plane_grid.frag'; Output='Generated/WorldReference/ShaderBytecode.ViewPlaneGridFrag.cs'; Class='ShaderBytecodeViewPlaneGridFrag' },
    @{ Source='SceneTerrain/scene.frag'; Output='Generated/ShaderBytecode.Frag.cs'; Class='ShaderBytecodeFrag' },
    @{ Source='SceneTerrain/scene.vert'; Output='Generated/ShaderBytecode.Vert.cs'; Class='ShaderBytecodeVert' },
    @{ Source='SceneTerrain/terrain.frag'; Output='Generated/GridTerrain/ShaderBytecode.TerrainFrag.cs'; Class='ShaderBytecodeTerrainFrag' },
    @{ Source='SceneTerrain/terrain.vert'; Output='Generated/GridTerrain/ShaderBytecode.TerrainVert.cs'; Class='ShaderBytecodeTerrainVert' },
    @{ Source='VectorScale/editor_scale_indicator.frag'; Output='Generated/EditorOverlays/ShaderBytecode.ScaleIndicatorFrag.cs'; Class='ShaderBytecodeScaleIndicatorFrag' },
    @{ Source='VectorScale/editor_vector_overlay.frag'; Output='Generated/EditorOverlays/ShaderBytecode.EditorVectorOverlayFrag.cs'; Class='ShaderBytecodeEditorVectorOverlayFrag' },
    @{ Source='VectorScale/editor_vector_overlay.vert'; Output='Generated/EditorOverlays/ShaderBytecode.EditorVectorOverlayVert.cs'; Class='ShaderBytecodeEditorVectorOverlayVert' },
    @{ Source='WorldAxes/editor_world_axes.frag'; Output='Generated/Navigation/ShaderBytecode.WorldAxesFrag.cs'; Class='ShaderBytecodeWorldAxesFrag' },
    @{ Source='WorldAxes/editor_world_origin.frag'; Output='Generated/Navigation/ShaderBytecode.WorldOriginFrag.cs'; Class='ShaderBytecodeWorldOriginFrag' },
    @{ Source='WorldAxes/editor_world_reference_grid.frag'; Output='Generated/WorldReference/ShaderBytecode.WorldReferenceGridFrag.cs'; Class='ShaderBytecodeWorldReferenceGridFrag' }
)
$failures = [System.Collections.Generic.List[string]]::new()
foreach ($module in $modules) {
    $source = Join-Path $PSScriptRoot ('Sources\' + $module.Source)
    $output = Join-Path $PSScriptRoot $module.Output
    $spv = Join-Path $artifactRoot ([IO.Path]::GetFileName($source) + '.spv')
    & $compiler -O $source -o $spv
    if ($LASTEXITCODE -ne 0) { throw "GLSL compile failed: $source" }
    $bytes = [IO.File]::ReadAllBytes($spv)
    if (($bytes.Length % 4) -ne 0 -or $bytes.Length -lt 20) { throw "Invalid SPIR-V byte length: $spv" }
    $words = [uint32[]]::new($bytes.Length / 4)
    [Buffer]::BlockCopy($bytes, 0, $words, 0, $bytes.Length)
    $relative = [IO.Path]::GetRelativePath($root, $output)
    $namespace = 'XuanYu.Render.Vulkan.Pipeline'
    $parts = [System.Collections.Generic.List[string]]::new()
    $partFiles = [System.Collections.Generic.List[object]]::new()
    for ($offset = 0; $offset -lt $words.Length; $offset += 640) {
        $partNo = $parts.Count + 1
        $partClass = "$($module.Class)GeneratedPart$('{0:D2}' -f $partNo)"
        $partRelative = [IO.Path]::Combine([IO.Path]::GetDirectoryName($relative), "$($module.Class).GeneratedPart$('{0:D2}' -f $partNo).cs")
        $take = [Math]::Min(640, $words.Length - $offset)
        $lines = [System.Collections.Generic.List[string]]::new()
        $lines.Add('// Generated by Generate-Shaders.ps1. Do not edit.')
        $lines.Add("namespace $namespace;")
        $lines.Add("internal static class $partClass")
        $lines.Add('{')
        $lines.Add('    internal static readonly uint[] Code =')
        $lines.Add('    [')
        for ($i = $offset; $i -lt ($offset + $take); $i += 8) {
            $last = [Math]::Min($i + 7, $offset + $take - 1)
            $row = for ($j = $i; $j -le $last; $j++) { '0x{0:X8}u' -f $words[$j] }
            $lines.Add('        ' + ($row -join ', ') + ',')
        }
        $lines.Add('    ];'); $lines.Add('}')
        $partFiles.Add(@{ Path=(Join-Path $root $partRelative); Text=($lines -join "`r`n") + "`r`n" })
        $parts.Add($partClass)
    }
    $wrapper = [System.Collections.Generic.List[string]]::new()
    $wrapper.Add('// Generated by Generate-Shaders.ps1. Do not edit.')
    $wrapper.Add("namespace $namespace;")
    $wrapper.Add("internal static class $($module.Class)")
    $wrapper.Add('{'); $wrapper.Add('    internal static readonly uint[] Code =')
    $wrapper.Add('    [')
    foreach ($part in $parts) { $wrapper.Add("        .. $part.Code,") }
    $wrapper.Add('    ];'); $wrapper.Add('}')
    $all = @(@{ Path=$output; Text=($wrapper -join "`r`n") + "`r`n" }) + $partFiles.ToArray()
    foreach ($file in $all) {
        $existing = if (Test-Path -LiteralPath $file.Path) { [IO.File]::ReadAllText($file.Path) } else { '' }
        if ($existing -cne $file.Text) {
            if ($Generate) { [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($file.Path)) | Out-Null; [IO.File]::WriteAllText($file.Path, $file.Text, [Text.UTF8Encoding]::new($false)) }
            else { $failures.Add([IO.Path]::GetRelativePath($root, $file.Path)) }
        }
    }
    $expectedPartPaths = @($partFiles | ForEach-Object { [IO.Path]::GetFullPath($_.Path) })
    $outputDirectory = [IO.Path]::GetDirectoryName($output)
    foreach ($existingPart in (Get-ChildItem -LiteralPath $outputDirectory -Filter "$($module.Class).GeneratedPart*.cs" -File -ErrorAction SilentlyContinue)) {
        if ($existingPart.FullName -notin $expectedPartPaths) {
            if ($Generate) { Remove-Item -LiteralPath $existingPart.FullName }
            else { $failures.Add([IO.Path]::GetRelativePath($root, $existingPart.FullName)) }
        }
    }
    Write-Output ("{0}: {1} words SHA256={2}" -f $module.Source, $words.Length, (Get-FileHash -Algorithm SHA256 -LiteralPath $spv).Hash)
}
if ($failures.Count) { throw ('Generated shader output mismatch: ' + ($failures -join ', ')) }
Write-Output "Shader contract verified: $($modules.Count) GLSL modules compiled with glslc -O; outputs match."
